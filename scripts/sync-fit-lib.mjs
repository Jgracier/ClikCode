#!/usr/bin/env node
/**
 * Vendors ClikDeploy's shared local-fit library and its signed catalog snapshot.
 *
 *   node scripts/sync-fit-lib.mjs          copy from $CLIKDEPLOY_REPO (default ~/projects/cd-streamline)
 *   node scripts/sync-fit-lib.mjs --check  exit 1 if the checked-in copy differs from the source
 *
 * packages/clikmodels/src/local-fit/*.ts  ->  src/local-models/shared/*.ts
 *   Each file gets a generated header carrying the SHA-256 of its body, and extensionless
 *   relative imports become `.js` (ClikCode's ESM resolution). Tests are not copied.
 *   shared.vitest.test.ts re-hashes every vendored body against its header, so a hand edit
 *   fails with no ClikDeploy checkout present, and compares against the source when there is one.
 * packages/clikmodels/src/local-catalog/signed.json  ->  src/local-models/catalog.snapshot.json
 *   Copied byte for byte; its Ed25519 signature is what makes it trustworthy, not this script.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SHARED_DIR = join(ROOT, 'src', 'local-models', 'shared');
export const SNAPSHOT_FILE = join(ROOT, 'src', 'local-models', 'catalog.snapshot.json');
const HEADER_MARK = '// content-sha256: ';

export function sourceRepo() {
  return process.env.CLIKDEPLOY_REPO || join(homedir(), 'projects', 'cd-streamline');
}

export function sourcePaths(repo = sourceRepo()) {
  return {
    fitDir: join(repo, 'packages', 'clikmodels', 'src', 'local-fit'),
    signed: join(repo, 'packages', 'clikmodels', 'src', 'local-catalog', 'signed.json'),
  };
}

const sha256 = (text) => createHash('sha256').update(text).digest('hex');

/** The vendored body of one source file: relative imports and re-exports get a .js extension. */
export function vendoredBody(source) {
  return source.replace(/(\bfrom\s+')(\.{1,2}\/[^']+)(')/g, (whole, open, path, close) => (/\.[a-z]+$/.test(path) ? whole : `${open}${path}.js${close}`));
}

export function withHeader(name, body) {
  return [
    '// GENERATED by scripts/sync-fit-lib.mjs from ClikDeploy packages/clikmodels/src/local-fit/' + name + '. Do not edit:',
    '// change it in ClikDeploy and run the script again. shared.vitest.test.ts fails on a drifted copy.',
    `${HEADER_MARK}${sha256(body)}`,
    '',
    body,
  ].join('\n');
}

/** The body and recorded hash of a vendored file. */
export function splitVendored(text) {
  const lines = text.split('\n');
  const hashLine = lines[2] ?? '';
  return { recorded: hashLine.startsWith(HEADER_MARK) ? hashLine.slice(HEADER_MARK.length) : undefined, body: lines.slice(4).join('\n') };
}

export function libraryFiles(fitDir) {
  return readdirSync(fitDir).filter((name) => name.endsWith('.ts') && !name.includes('.test.') && !name.includes('.vitest.')).sort();
}

/** What the vendored files should contain, by file name. */
export function expectedFiles(repo = sourceRepo()) {
  const { fitDir } = sourcePaths(repo);
  return Object.fromEntries(libraryFiles(fitDir).map((name) => [name, withHeader(name, vendoredBody(readFileSync(join(fitDir, name), 'utf8')))]));
}

function main() {
  const repo = sourceRepo();
  const { signed } = sourcePaths(repo);
  if (!existsSync(signed)) {
    console.error(`No ClikDeploy checkout at ${repo}; set CLIKDEPLOY_REPO.`);
    process.exit(2);
  }
  const files = expectedFiles(repo);
  const snapshot = readFileSync(signed, 'utf8');
  if (process.argv.includes('--check')) {
    const stale = Object.entries(files).filter(([name, text]) => !existsSync(join(SHARED_DIR, name)) || readFileSync(join(SHARED_DIR, name), 'utf8') !== text).map(([name]) => name);
    if (!existsSync(SNAPSHOT_FILE) || readFileSync(SNAPSHOT_FILE, 'utf8') !== snapshot) stale.push('catalog.snapshot.json');
    if (stale.length) { console.error(`Out of date with ${repo}: ${stale.join(', ')}. Run: node scripts/sync-fit-lib.mjs`); process.exit(1); }
    return;
  }
  rmSync(SHARED_DIR, { recursive: true, force: true });
  mkdirSync(SHARED_DIR, { recursive: true });
  for (const [name, text] of Object.entries(files)) writeFileSync(join(SHARED_DIR, name), text);
  writeFileSync(SNAPSHOT_FILE, snapshot);
  console.log(`Vendored ${Object.keys(files).length} files and the catalog snapshot from ${repo}.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
